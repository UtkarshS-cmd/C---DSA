// 2D Array Basics
// Approach: Learn how to traverse 2D arrays clearly.
// Beginner-friendly implementation for DSA practice.

#include <bits/stdc++.h>
using namespace std;

int main() { vector<vector<int>> a = {{1,2,3},{4,5,6}}; for (auto &row : a) for (int x : row) cout << x << ' '; cout << "\n"; return 0; }


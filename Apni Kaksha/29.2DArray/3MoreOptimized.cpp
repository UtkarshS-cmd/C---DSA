// 2D Array Basics
// Approach: Learn how to traverse 2D arrays clearly.
// Beginner-friendly implementation for DSA practice.

#include <bits/stdc++.h>
using namespace std;

int main() { vector<vector<int>> a = {{1,2,3},{4,5,6}}; for (int i = 0; i < (int)a.size(); ++i) for (int j = 0; j < (int)a[i].size(); ++j) cout << a[i][j] << ' '; cout << "\n"; return 0; }


// 2D Array Basics
// Approach: Learn how to traverse 2D arrays clearly.
// Beginner-friendly implementation for DSA practice.

#include <bits/stdc++.h>
using namespace std;

int main() { int a[2][3] = {{1,2,3},{4,5,6}}; for (int i = 0; i < 2; ++i) for (int j = 0; j < 3; ++j) cout << a[i][j] << ' '; cout << "\n"; return 0; }

